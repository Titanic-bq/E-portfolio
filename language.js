const getTranslation = (copy, key) =>
  key.split(".").reduce((value, part) => value?.[part], copy);
window.portfolioText = (key) =>
  getTranslation(
    translations[document.documentElement.lang] ?? translations.en,
    key,
  );

const applyLanguage = (language) => {
  const copy = translations[language] ?? translations.en;
  document.documentElement.lang = language;
  document.title = getTranslation(copy, "page.title");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const text = getTranslation(copy, element.dataset.i18n);
    if (text !== undefined) element.textContent = text;
  });

  const attributes = {
    "aria-label": "data-i18n-aria-label",
    alt: "data-i18n-alt",
    placeholder: "data-i18n-placeholder",
    content: "data-i18n-content",
  };

  Object.entries(attributes).forEach(([attribute, dataAttribute]) => {
    document.querySelectorAll(`[${dataAttribute}]`).forEach((element) => {
      const text = getTranslation(copy, element.getAttribute(dataAttribute));
      if (text !== undefined) element.setAttribute(attribute, text);
    });
  });

  const themeToggle = document.querySelector("[data-theme-toggle]");
  if (themeToggle) {
    const isLight = document.documentElement.dataset.theme === "light";
    themeToggle.setAttribute(
      "aria-label",
      getTranslation(
        copy,
        isLight ? "theme.switchToDark" : "theme.switchToLight",
      ),
    );
    themeToggle.setAttribute("aria-pressed", String(isLight));
  }

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.setAttribute(
      "aria-pressed",
      String(button.dataset.language === language),
    );
  });

  try {
    localStorage.setItem("portfolio-language", language);
  } catch {
    // Language switching still works when browser storage is unavailable.
  }
};

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () =>
    applyLanguage(button.dataset.language),
  );
});

let savedLanguage = "en";
try {
  savedLanguage = localStorage.getItem("portfolio-language") ?? "en";
} catch {
  savedLanguage = "en";
}
applyLanguage(savedLanguage);
