const applyLanguage = (language) => {
  const copy = translations[language] ?? translations.en;

  document.documentElement.lang = language;
  document.title = copy["page.title"];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = copy[element.dataset.i18n];
    if (translation !== undefined) element.textContent = translation;
  });

  const attributes = [
    ["data-i18n-aria-label", "aria-label"],
    ["data-i18n-alt", "alt"],
    ["data-i18n-placeholder", "placeholder"],
    ["data-i18n-content", "content"],
  ];

  attributes.forEach(([key, attribute]) => {
    document.querySelectorAll(`[${key}]`).forEach((element) => {
      const translation = copy[element.getAttribute(key)];
      if (translation !== undefined)
        element.setAttribute(attribute, translation);
    });
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.setAttribute(
      "aria-pressed",
      String(button.dataset.language === language),
    );
  });

  try {
    localStorage.setItem("portfolio-language", language);
  } catch {
    // Language switching still works when browser storage is unavailable.
  }
};

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () =>
    applyLanguage(button.dataset.language),
  );
});

let savedLanguage = "en";
try {
  savedLanguage = localStorage.getItem("portfolio-language") ?? "en";
} catch {
  savedLanguage = "en";
}
applyLanguage(savedLanguage);
